// ============================================================
// _pipeline/prompt —— 系统提示词
// ============================================================
// 2026-09-14：从 `prompt.ts` 迁成目录（AGENTS 6.5——要给它补单测，
// 实现和测试就必须同目录、都叫 index）。
//
// ⭐ 为什么从**常量**变成**函数**：必须告诉模型今天几号。
//
// 真机验收发现的 bug：用户问「即梦**今年**的营收」，模型去搜
// 「即梦 **2025** 营收」。根因不是模型笨——是**我们没给它时间**，
// 它只能拿**训练数据截止时间**当"现在"，于是把 2025 当成今年
// （实测当天是 2026-09-14）。
//
// 两家参考都有对应机制：
//   - DSH `packages/context/time-context/`：每步注入带来源标记的时间读数
//   - pi：`get_current_time` 工具，让模型自己问
// 我们选 DSH 那条路（注入上下文），理由就是这次的失败模式：
// **模型不知道自己不知道**——它压根不会去调那个工具。
//
// ⚠️ 已知代价：system prompt 因此每天变一次，DeepSeek 的上下文缓存
// 会按天失效（天粒度，影响很小）。真要省，可以只给日期不给时分。
// ============================================================

/**
 * 把「现在」渲染成给人/模型看的一行，**带时区**。
 *
 * 为什么要带时区：不给的话，"18:43"对模型来说是悬浮的——它没法判断
 * 这个时间属于哪个区域，也就没法正确换算"昨天""北京时间早上"之类的说法。
 *
 * @param now - 要渲染的时刻（默认取当前）
 * @param timeZone - IANA 时区名；不传用运行环境的时区（渲染与判断都按它）
 */
export function formatCurrentTime(
  now: Date = new Date(),
  timeZone?: string,
): string {
  const zone = timeZone ?? Intl.DateTimeFormat().resolvedOptions().timeZone;
  const stamp = new Intl.DateTimeFormat("zh-CN", {
    dateStyle: "full", // 2026年9月14日星期一
    timeStyle: "short", // 18:43
    timeZone: zone,
  }).format(now);
  return `${stamp}（时区 ${zone}）`;
}

/**
 * 组装本次请求的系统提示词。
 *
 * @param now - 用于渲染"当前时间"的时刻（注入是为了可测：固定时刻断言输出）
 * @param skillCatalog - 技能清单，由调用方算好传进来
 *   （`buildSkillCatalog(loadSkills(技能根).skills)`）。**空串 = 这台机器没装技能
 *   ⇒ 整节省略**（宁可没有这一节，也不留一个空标题：空标题会让模型以为"有技能
 *   但没列出来"，然后去猜名字）。
 *
 *   ⭐ 为什么清单是**参数**、这一层不自己去读文件：① 保持纯函数（固定字符串进、
 *   固定字符串出，好测）② "技能根在哪"由调用方决定 —— 将来它按工作区变的时候，
 *   这里一行都不用动。清单的**生成规则**（只含 model-invocable、markdown 形态）
 *   在 `lib/skill`，那里有它自己的单测。
 */
export function buildSystemPrompt(
  now: Date = new Date(),
  skillCatalog = "",
  toolGuidelines: Array<{ name: string; text: string }> = [],
): string {
  // 有技能才有"技能"这一节（没有就整节省略，见函数注释：不留空标题）
  const hasSkills = skillCatalog.trim() !== "";
  return [
    "你是 statve，一个帮助初学者理解 AI Agent 核心机制的教学助手。",
    "你运行在一个安全工作区（workspace/）内，只能通过工具与文件交互，不能直接改动文件系统。",
    "",
    "## 当前时间",
    `现在是：${formatCurrentTime(now)}。`,
    "涉及「今年 / 最近 / 最新 / 上个月」这类**相对时间**时，一律以上面这个时间为准。你的训练数据截止时间不是现在——不要拿它当当前时间。",
    "",
    "## 工具使用原则",
    // ⚠️ **这段里不写任何"工具专属的规矩"**（2026-09-16 定，C34）。两个阶段各删了一半：
    //   ① 先删"手抄的工具**名字**"（每个工具"是什么"由随请求发来的 `tools` 定义承载 ——
    //      那是权威，改工具时同一个文件里就看见）。实测：那份手写清单从 Phase 3（8 个工具）
    //      活到 14 个工具，中途搬了三次家，**第 14 个（`skill`）就漏了**。
    //   ② 再删"手写的工具**规矩**"（就是下面这些 `- 工具名：…` 条目）—— 它们现在住在
    //      **各工具自己的文件里**（`RegisteredTool.guidelines`），由使用端收集后传进来渲染。
    // **判据（一条就够）：文本住哪个文件，决定关联的强弱。** 住工具文件 = 改工具就看得见、
    // 工具删了它跟着消失；住这个文件 = **谁都不欠它一次同步**。
    // 这里只留**不点名任何工具**的通用规矩。
    // 这条规则的可执行形式：prompt/index.test.ts 的「工具专属的规矩只能来自工具投稿」。
    "- 只有用户明确要求「列出 / 读取 / 写入 / 修改 / 删除 / 搜索 / 执行命令」时才调用工具；概念原理类问题直接回答，不要硬套工具。",
    "- 一次只调用当前步骤真正需要的工具；拿到工具结果后必须基于真实结果回答，绝不编造文件内容。",
    "- 工具失败或读不到内容时，如实说明，不要假装成功。",
    "- 写 / 改 / 删文件会弹框请用户确认；被拒绝时工具结果会报错，如实向用户说明，不要反复重试同一操作。",
    // 工具自己声明的规矩（各工具文件里 → ToolRegistry.guidelines() 收集 → 这里渲染）
    ...toolGuidelines.map(({ name, text }) => `- ${name}：${text}`),
    "",
    // 技能清单（C8）：**没有技能就没有这一节**（见函数注释：不留空标题）
    ...(hasSkills ? ["## 技能", skillCatalog, ""] : []),
    // 出处：codex `codex-rs/ext/web-search/web_run_description.md` 的 Decision boundary
    // ⭐ 抄的是**决策边界这条路线**，不抄它的产品机制（ref_id / wordlim / reddit 例外…）。
    // 这段补的是 2026-09-14 那个 bug 的**另一半**：光说"现在是几号"只管住了年份，
    // 管不住"该不该信自己的记忆"。
    "## 什么时候必须联网",
    "你的记忆会过期——**训练数据有截止时间，而世界一直在变**。做任何假设之前先问自己一句：「这件事**随时间会变**吗？」只要它有**哪怕 10% 的可能已经变了**，就必须去查，不要凭记忆回答。",
    "必须联网的情况：",
    "- 信息最近可能变过：新闻、价格、法律 / 规章 / 标准、日程、产品规格、赛事比分、经济数据、公司与政府的公开人物（CEO、总统…）、软件库版本、汇率",
    "- 用户要你给**会花不少时间或钱**的建议（选产品、餐厅、行程…）",
    "- 用户要**直接引文、链接或精确出处**",
    // ⚠️ 原来这条末尾是「（这时用 web_fetch）」—— 2026-09-16 C34 重验时按归属规则**搬走了**：
    // 那半句讲的是"什么时候用 web_fetch"，是那个工具专属的规矩，该住在 `lib/tools/web-fetch/`。
    // 留在这里会让"手写的工具名"从防线里漏过去（防线只看行首，抓不住夹在句中的引用）。
    "- 提到某个具体的页面 / 论文 / 数据集 / PDF，而你手上没有它的内容",
    "- 你自己也不确定，或者话题冷门、新兴",
    "- 准确性代价高（医疗、法律、金融）——这类**默认就该查**",
    "- 用户明确说了「搜一下 / 查证 / 看看最新的」",
    "**拿不准的时候，倾向于去查。**",
    "另外：凡是涉及年份、季度、「今年」这类相对时间，一律以上面「当前时间」里那一年为准，**不要用训练数据里的年份**。",
    "",
    "## 引用来源",
    "- 用到网页内容，就把链接放在**支撑那句话的附近**，不要全堆在回答末尾。",
    "- 写成 `[有描述性的标题](https://…)`，**不要只贴裸 URL**。",
    "- 链到**具体页面**，不要链搜索结果页。",
    "- 不要**大段逐字照搬**原文；用自己的话概括，确实需要原文时只引关键的一两句。",
    "",
    "## 输出要求",
    "- 始终用中文回答。",
    "- 用 Markdown 排版：善用标题、列表、表格；代码示例用带语言标注的代码块。",
    "- **任务优先于教学**：用户让你执行/验证/操作时，先直接给出结果（成功/失败/数据），不要借题发挥展开教学。",
    "- 工具失败时：如实复述错误和退出码，一句话说明失败原因即可；只有用户明确追问机制时才展开讲解。",
    "- 解释概念时：先一句话结论 → 再展开讲机制 → 最后给一个最小示例或类比。",
  ].join("\n");
}
