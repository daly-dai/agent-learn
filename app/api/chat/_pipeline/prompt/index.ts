//
// ⭐ 为什么从**常量**变成**函数**：必须告诉模型今天几号。
//
// 真机验收发现的 bug：用户问「即梦**今年**的营收」，模型去搜
// 「即梦 **2025** 营收」。根因不是模型笨——是**我们没给它时间**，
// 它只能拿**训练数据截止时间**当"现在"，于是把 2025 当成今年
// （实测当天是 2026-09-14）。
//
// 两家参考都有对应机制：
//   - DSH `packages/context/time-context/`：每步注入带来源标记的时间读数
//   - pi：`get_current_time` 工具，让模型自己问
// 我们选 DSH 那条路（注入上下文），理由就是这次的失败模式：
// **模型不知道自己不知道**——它压根不会去调那个工具。
//
// ⚠️ 已知代价：system prompt 因此每天变一次，DeepSeek 的上下文缓存
// 会按天失效（天粒度，影响很小）。真要省，可以只给日期不给时分。
// ============================================================

/**
 * 把「现在」渲染成给人/模型看的一行，**带时区**。
 *
 * 为什么要带时区：不给的话，"18:43"对模型来说是悬浮的——它没法判断
 * 这个时间属于哪个区域，也就没法正确换算"昨天""北京时间早上"之类的说法。
 *
 * @param now - 要渲染的时刻（默认取当前）
 * @param timeZone - IANA 时区名；不传用运行环境的时区（渲染与判断都按它）
 */
export function formatCurrentTime(
  now: Date = new Date(),
  timeZone?: string,
): string {
  const zone = timeZone ?? Intl.DateTimeFormat().resolvedOptions().timeZone;
  const stamp = new Intl.DateTimeFormat("zh-CN", {
    dateStyle: "full", // 2026年9月14日星期一
    timeStyle: "short", // 18:43
    timeZone: zone,
  }).format(now);
  return `${stamp}（时区 ${zone}）`;
}

